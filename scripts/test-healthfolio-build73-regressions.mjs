#!/usr/bin/env node
import { readFileSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import assert from 'node:assert/strict';

const root = process.cwd();

function read(relativePath) {
  return readFileSync(join(root, relativePath), 'utf8');
}

function latestMatchingMigration(suffix) {
  const matchingMigrationNames = readdirSync(join(root, 'supabase/migrations'))
    .filter((name) => name.endsWith(suffix))
    .sort((left, right) => left.localeCompare(right));

  assert.ok(
    matchingMigrationNames.length > 0,
    `${suffix} migration must be generated by the Supabase CLI`,
  );

  const migrationName = matchingMigrationNames.at(-1);
  assert.ok(
    migrationName,
    `${suffix} migration selection must resolve to the newest matching file`,
  );

  return read(`supabase/migrations/${migrationName}`);
}

const appConfig = JSON.parse(read('apps/mobile/app.json'));
const buildNumber = Number(appConfig.expo.ios.buildNumber);
assert.ok(buildNumber >= 73, 'The current release must retain all build 73 safeguards');
assert.doesNotMatch(
  JSON.stringify(appConfig.expo.android.permissions ?? []),
  /RECORD_AUDIO/,
  'HealthFolio must not request microphone access when the app has no audio feature',
);
assert.ok(
  appConfig.expo.android.blockedPermissions?.includes('android.permission.RECORD_AUDIO'),
  'Expo must block transitive microphone permission requests',
);

